// COLORIZE — global scope
// Classifies every character of the FINAL line text up front, so the color
// each character gets while typing never changes later (no "flash" recolor).
function classifyLine(text) {
  if (text.trimStart().startsWith('//')) return new Array(text.length).fill('c-gray');

  const classes = new Array(text.length).fill('c-white');
  let inString = false;
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (ch === '"') {
      classes[i] = 'c-orange';
      inString = !inString;
      i++;
      continue;
    }
    if (inString) { classes[i] = 'c-orange'; i++; continue; }
    if (text.startsWith('console', i)) {
      for (let k = 0; k < 7; k++) classes[i + k] = 'c-purple';
      i += 7;
      continue;
    }
    if (text.startsWith('log', i)) {
      for (let k = 0; k < 3; k++) classes[i + k] = 'c-blue';
      i += 3;
      continue;
    }
    const kwMatch = ['while', 'else', 'if'].find(kw => isKeywordAt(text, i, kw));
    if (kwMatch) {
      for (let k = 0; k < kwMatch.length; k++) classes[i + k] = 'c-accent';
      i += kwMatch.length;
      continue;
    }
    i++;
  }
  return classes;
}

function isKeywordAt(text, i, kw) {
  if (!text.startsWith(kw, i)) return false;
  const isWordChar = c => /[A-Za-z0-9_]/.test(c || '');
  return !isWordChar(text[i - 1]) && !isWordChar(text[i + kw.length]);
}

function escapeChar(c) {
  return c === '&' ? '&amp;' : c === '<' ? '&lt;' : c === '>' ? '&gt;' : c;
}

function renderColored(text, classes, upto) {
  let html = '', curCls = null, buf = '';
  for (let idx = 0; idx < upto; idx++) {
    const cls = classes[idx];
    if (cls !== curCls) {
      if (curCls !== null) html += `<span class="${curCls}">${buf}</span>`;
      curCls = cls; buf = '';
    }
    buf += escapeChar(text[idx]);
  }
  if (curCls !== null) html += `<span class="${curCls}">${buf}</span>`;
  return html;
}

// TYPEWRITER
function startTypewriter() {
  const tr = document.documentElement.lang !== 'en';
  const L = tr ? {
    c1: "// eduxperts — 2020'den beri",
    hi: 'console.log("Merhaba, biz EduXperts.");',
    cond: 'if (fikrin) {',
    yes: '  console.log("Birlikte yapalım.");',
    no: '  console.log("Birlikte bulalım.");',
    what: 'console.log("Eğitim, oyun, yazılım.");',
    own: 'console.log("Bir kısmı da bizim.");',
    end: '// ✓ hazırsan başlayalım.'
  } : {
    c1: '// eduxperts — since 2020',
    hi: 'console.log("Hello, we\'re EduXperts.");',
    cond: 'if (yourIdea) {',
    yes: '  console.log("We\'ll build it.");',
    no: '  console.log("Let\'s find it together.");',
    what: 'console.log("Education, games, software.");',
    own: 'console.log("Some of it is our own.");',
    end: '// ✓ ready when you are.'
  };
  const lines = [
    { text: L.c1, delay: 0 },
    { text: '', delay: 500 },
    { text: L.hi, delay: 800 },
    { text: '', delay: 2000 },
    { text: L.cond, delay: 2300 },
    { text: L.yes, delay: 3100 },
    { text: '} else {', delay: 4100 },
    { text: L.no, delay: 4600 },
    { text: '}', delay: 5700 },
    { text: '', delay: 6100 },
    { text: L.what, delay: 6400 },
    { text: L.own, delay: 7400 },
    { text: '', delay: 8400 },
    { text: L.end, delay: 8700, isLast: true },
  ];

  const codeBody = document.querySelector('.code-body');
  if (!codeBody) return;
  codeBody.innerHTML = '';

  lines.forEach(line => {
    setTimeout(() => {
      const div = document.createElement('div');
      div.className = 'code-line';
      if (!line.text) { codeBody.appendChild(div); return; }

      const plain = line.text;
      const classes = classifyLine(plain);
      let i = 0;
      codeBody.appendChild(div);

      const timer = setInterval(() => {
        i++;
        div.innerHTML = renderColored(plain, classes, i);
        if (i >= plain.length) {
          clearInterval(timer);
          if (line.isLast) {
            div.innerHTML = renderColored(plain, classes, i) + '<span class="cursor-blink">|</span>';
          }
        }
      }, 36);
    }, line.delay);
  });
}

